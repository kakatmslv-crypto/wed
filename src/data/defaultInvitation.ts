export function formatKhmerInvitationPlainText(data: InvitationData): string {
  return [
    data.ceremonyHeadline,
    '',
    'យើងខ្ញុំជាមាតាបិតាទាំងសងខាង៖',
    `• ${data.groomFather} និង ${data.groomMother}`,
    `• ${data.brideFather} និង ${data.brideMother}`,
    '',
    data.guestHonorific,
    data.invitationLead,
    '',
    `• កូនកំលោះ៖ ${data.groomName}`,
    `• កូនក្រមុំ៖ ${data.brideName}`,
    '',
    `• ${data.gregorianDate} (${data.lunarDate})`,
    `• វេលាម៉ោង៖ ${data.morningTime} (${data.morningActivity}) / ${data.noonTime} (${data.noonActivity})`,
    `• ទីតាំង៖ ${data.venueAddress}`,
    '',
    data.closingMessage,
  ].join('\n');
}
